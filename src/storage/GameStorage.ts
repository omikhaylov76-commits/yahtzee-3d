/**
 * Контракт хранилища партии (ADR 0005). Реализация изолирована — позже заменяется на
 * сервер без изменения ядра/UI. См. docs/architecture.md (storage/).
 */
import type { GameState } from '../core';

export interface GameStorage {
  /** Сохранить текущее состояние партии. Не должно бросать наружу (тихо игнорирует сбой). */
  save(state: GameState): void;
  /** Загрузить сохранённую партию или null (нет/повреждено/иная версия). */
  load(): GameState | null;
  /** Удалить сохранение (например, по «Новая игра»). */
  clear(): void;
}
