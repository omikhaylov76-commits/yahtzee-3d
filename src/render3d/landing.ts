/**
 * Способ приземления костей на значение из ядра (F4.3) — переключаемый флаг.
 * Меняется ОДНОЙ строкой, без правок логики, чтобы можно было быстро сравнить варианты
 * вживую и при необходимости откатиться.
 *
 * - 'reveal'   — «проявление при посадке» (по умолчанию): настоящая физика + точки
 *                проявляются уже на нужном значении. Без видимого доворота и без моргания.
 * - 'reorient' — доворот кости в покое (старый вариант, fallback-коммит 16f7676).
 * - 'relabel'  — мгновенная подмена значения в покое (чистый B): проще, но возможно
 *                видимое моргание цифр в кадре посадки.
 */
export type LandingMode = 'reveal' | 'reorient' | 'relabel';

export const LANDING_MODE: LandingMode = 'reveal';
