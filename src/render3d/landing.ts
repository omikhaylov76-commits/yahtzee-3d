/**
 * Способ приземления костей на значение из ядра (F4.3) — переключаемый флаг.
 * Меняется ОДНОЙ строкой, без правок логики, чтобы можно было быстро сравнить варианты
 * вживую и при необходимости откатиться.
 *
 * - 'presim'   — предрасчёт броска + воспроизведение (по умолчанию, вариант A): headless-
 *                симуляция записывает траекторию и грань приземления, точки переразмечаются
 *                ОДИН раз (чёткие/чёрные всё время), затем запись проигрывается. Кость честно
 *                ложится на число; ни доворота, ни моргания, ни серости.
 * - 'reveal'   — «проявление при посадке» (запасной, коммит e84f96f): точки притушены в
 *                полёте и проявляются на посадке. Требует доработки «чёткие точки всегда».
 * - 'reorient' — доворот кости в покое (fallback-коммит 16f7676).
 * - 'relabel'  — мгновенная подмена значения в покое (чистый B).
 */
export type LandingMode = 'presim' | 'reveal' | 'reorient' | 'relabel';

export const LANDING_MODE: LandingMode = 'presim';
