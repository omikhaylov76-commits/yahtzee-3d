import type { DieValue } from '../core';

/**
 * Изменился ли хоть один бросок по сравнению с предыдущим снимком (поэлементно, по позиции) — 2.1.e-1.
 *
 * Используется как АВТОРИТЕТНЫЙ ПО ЗНАЧЕНИЯМ триггер приземления 3D-костей: вместо опоры лишь на
 * транзиентное событие `dice:rolled` поле сравнивает «отыгранные» значения с актуальными `state.dice`
 * и, если они РАСХОДЯТСЯ, докатывает кости к серверным значениям. Так грани верны и в онлайне (свой и
 * чужой бросок), даже если событие не отработало по таймингу/ленивой загрузке 3D. Сами значения для
 * доворота поле берёт из `state.dice`, поэтому достаточно булева факта «что-то изменилось». Чистая
 * функция — покрыта юнит-тестом (слой Three.js/Rapier headless не тестируется).
 *
 * Длины всегда равны (всегда 5 костей); на всякий случай сравниваем по минимуму.
 *
 * Граница by-value: неудержанная кость, перекатившаяся в ТО ЖЕ значение, расхождения не даёт. Это НЕ
 * порождает рассинхрон — её грань и так верна (значение не менялось); анимацию такой кости, если рядом
 * изменилась другая, докрывает presim (он катит ВСЕ неудержанные), а в одиночном корнер-кейсе её
 * докрывает событийный путь. Десинхронизации значений нет ни в одном случае.
 */
export function valuesDiffer(prev: readonly DieValue[], next: readonly DieValue[]): boolean {
  const n = Math.min(prev.length, next.length);
  for (let i = 0; i < n; i++) {
    if (prev[i] !== next[i]) return true;
  }
  return false;
}
