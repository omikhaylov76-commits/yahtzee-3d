/**
 * Нормализация/валидация имени игрока (2.2.b) — ЧИСТЫЙ модуль (без DOM/Node), поэтому импортируется
 * И клиентом (src/, мгновенный фидбэк), И сервером (server/, авторитетная очистка) и тестируется
 * (names.test.ts). Один источник правды по правилам имени: та же функция переиспользуется для имени
 * профиля в Вехе 2.3 — переделывать не придётся. Дедуп одинаковых имён в комнате — серверная вещь
 * (зависит от состава), он в server/platform/seating.ts.
 *
 * Что делает `normalizeName`:
 * - выравнивает Unicode (NFC), чтобы «é» в разных записях считались одной буквой;
 * - вырезает невидимые/управляющие/директивные символы, которыми можно подделать отображение или
 *   протащить разметку: C0/C1-control + DEL, soft hyphen, zero-width семью, bidi-директивы, `<`/`>`;
 * - схлопывает любые пробелы в один и обрезает по краям;
 * - ограничивает длину (по кодпойнтам — как `cleanName`/`normalizeCode` в codebase; графемный
 *   разрез намеренно не делаем: `Intl.Segmenter` не типизирован в ES2020-lib клиента, а имена коротки
 *   и ZWJ уже вырезан, так что разрыв кластера маловероятен и некритичен).
 *
 * Пустая строка на выходе = «валидного имени нет» — дефолт «Player N» подставляет СЕРВЕР (он знает
 * номер места); сюда seat не тащим, чтобы модуль остался игро-НЕзависимой платформой (ADR-0011).
 */

/** Максимальная длина имени (кодпойнтов). Один источник для клиента (инпут) и сервера (очистка). */
export const MAX_NAME_LEN = 20;

/**
 * Разрешён ли кодпойнт в имени. Запрещаем целиком невидимое/опасное; всё видимое (буквы любых
 * алфавитов, цифры, пунктуация, одиночные эмодзи) — оставляем.
 */
function isAllowed(cp: number): boolean {
  if (cp >= 0x09 && cp <= 0x0d) return true; // пробельные control (tab/LF/VT/FF/CR) — станут пробелом при схлопе
  if (cp <= 0x1f || (cp >= 0x7f && cp <= 0x9f)) return false; // прочие C0/C1-control + DEL
  if (cp === 0x00ad) return false; // soft hyphen — невидимый перенос
  if ((cp >= 0x200b && cp <= 0x200f) || cp === 0x2060 || cp === 0xfeff) return false; // zero-width/LRM/RLM/WJ/BOM
  if ((cp >= 0x202a && cp <= 0x202e) || (cp >= 0x2066 && cp <= 0x2069)) return false; // bidi embed/override/isolate
  // Прочие «невидимые», проходящие мимо классических классов: ими тоже можно собрать «пустое» имя.
  if (cp === 0x115f || cp === 0x1160 || cp === 0x3164 || cp === 0xffa0) return false; // Hangul fillers
  if (cp === 0x180e || cp === 0x2800) return false; // Mongolian vowel separator, Braille blank
  if (cp === 0x3c || cp === 0x3e) return false; // '<' '>' — анти-XSS (как в прежнем cleanName)
  return true;
}

/**
 * Привести имя к каноничному безопасному виду. `''` на выходе означает «имени нет» (вызывающий решает,
 * чем заменить: сервер — на «Player N», клиент — шлёт `undefined`). Идемпотентна: повторный прогон
 * результата ничего не меняет.
 */
export function normalizeName(raw: string | undefined): string {
  const cleaned = [...(raw ?? '').normalize('NFC')]
    .filter((ch) => isAllowed(ch.codePointAt(0) ?? 0))
    .join('')
    .replace(/\s+/gu, ' ') // любые пробелы (вкл. nbsp/ideographic) → один обычный
    .trim();
  // Обрезаем по кодпойнтам; финальный trim — на случай, если срез пришёлся на пробел.
  return [...cleaned].slice(0, MAX_NAME_LEN).join('').trim();
}
